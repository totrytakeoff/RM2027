#ifndef MC02_RESOURCES_H
#define MC02_RESOURCES_H
#define MC02_FDCAN_CLOCK_HZ 80000000U
#define MC02_CAN_RAM_WORDS 2560U
#define MC02_CAN_SLOT_WORDS 512U
#define MC02_CAN_STD_FILTERS 16U
#define MC02_CAN_EXT_FILTERS 8U
#define MC02_CAN_RX0_ELEMENTS 32U
#define MC02_CAN_RX1_ELEMENTS 8U
#define MC02_CAN_TX_BUFFERS 3U
#define MC02_CAN_TX_EVENTS 3U
#define MC02_CAN_USED_WORDS (MC02_CAN_STD_FILTERS + 2U*MC02_CAN_EXT_FILTERS + \
    4U*MC02_CAN_RX0_ELEMENTS + 4U*MC02_CAN_RX1_ELEMENTS + \
    4U*MC02_CAN_TX_BUFFERS + 2U*MC02_CAN_TX_EVENTS)
#define MC02_CAN_SOFTWARE_DEPTH 64U
#define MC02_SERIAL_SOFTWARE_DEPTH 32U
#define MC02_SERIAL_DMA_BYTES 512U
#define MC02_SERIAL_TX_BYTES 256U
#define MC02_SERIAL_TX_SLOTS 2U
#define MC02_SERIAL_ABORT_TIMEOUT_MS 50U
#define MC02_SERIAL_RECOVERY_ATTEMPTS 3U
_Static_assert(MC02_CAN_USED_WORDS <= MC02_CAN_SLOT_WORDS, "FDCAN region overflow");
_Static_assert(3U * MC02_CAN_SLOT_WORDS <= MC02_CAN_RAM_WORDS, "FDCAN shared RAM overflow");
_Static_assert(MC02_CAN_TX_BUFFERS==3U,"transport dedicated TX slots must match board");
#endif
